    private byte[] hexToByteArray(String[] arr) {
        if (arr == null) return new byte[0];

        byte[] result = new byte[arr.length];
        for (int i = 0; i < arr.length; i++) {
            // Parse each hex string into a byte
            result[i] = (byte) Integer.parseInt(arr[i], 16);
        }
        return result;
    }

